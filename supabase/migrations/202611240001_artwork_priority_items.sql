create table public.artwork_priority_items (
  id bigint generated by default as identity primary key,
  production_job_id bigint not null references public.production_jobs(id) on delete cascade,
  employee_profile_id uuid not null references public.employee_profiles(id) on delete cascade,
  needs_paint boolean not null default false,
  needs_powder_coat boolean not null default false,
  needs_prep boolean not null default false,
  needs_touch_up boolean not null default false,
  other_requirements text,
  notes text,
  status text not null default 'Open' check (status in ('Open', 'Completed')),
  created_by uuid references auth.users(id) on delete set null,
  completed_at timestamptz,
  completed_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint artwork_priority_items_job_employee_key unique (production_job_id, employee_profile_id)
);

create index artwork_priority_items_employee_status_idx
  on public.artwork_priority_items (employee_profile_id, status, created_at desc);

alter table public.artwork_priority_items enable row level security;

grant select, insert, update, delete on public.artwork_priority_items to authenticated;
grant usage, select on sequence public.artwork_priority_items_id_seq to authenticated;

create policy "Admins manage artwork priority items"
  on public.artwork_priority_items
  for all
  to authenticated
  using ((select public.mw_calendar_is_administrator()))
  with check ((select public.mw_calendar_is_administrator()));

create policy "Employees read their own artwork priority items"
  on public.artwork_priority_items
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.employee_profiles employee
      where employee.id = artwork_priority_items.employee_profile_id
        and employee.auth_user_id = (select auth.uid())
        and employee.is_active is true
    )
  );

create policy "Employees update their own artwork priority items"
  on public.artwork_priority_items
  for update
  to authenticated
  using (
    exists (
      select 1
      from public.employee_profiles employee
      where employee.id = artwork_priority_items.employee_profile_id
        and employee.auth_user_id = (select auth.uid())
        and employee.is_active is true
    )
  )
  with check (
    exists (
      select 1
      from public.employee_profiles employee
      where employee.id = artwork_priority_items.employee_profile_id
        and employee.auth_user_id = (select auth.uid())
        and employee.is_active is true
    )
  );