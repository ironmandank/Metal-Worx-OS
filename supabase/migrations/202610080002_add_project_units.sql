with check (
  exists (
    select 1 from public.employee_profiles employee
    where employee.auth_user_id = (select auth.uid())
      and employee.is_active = true
  )
);

create or replace function public.mw_touch_project_unit()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at := now();
  if new.handoff_status in ('Picked Up', 'Delivered') or new.status = 'Complete' then
    new.completed_at := coalesce(new.completed_at, now());
  elsif new.handoff_status not in ('Picked Up', 'Delivered') and new.status <> 'Complete' then
    new.completed_at := null;
  end if;
  return new;
end;
$$;

revoke all on function public.mw_touch_project_unit() from public, anon, authenticated;

drop trigger if exists mw_project_units_touch on public.project_units;
create trigger mw_project_units_touch
before insert or update on public.project_units
for each row execute function public.mw_touch_project_unit();

comment on table public.project_units is
